create function public.fhsis_require_complete_manual_values(p_report_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare v_missing_count integer;
begin
  select count(*) into v_missing_count
  from public.fhsis_reports r
  join public.fhsis_template_required_fields required_field
    on required_field.report_type = r.report_type
   and required_field.template_version = r.template_version
  left join public.fhsis_report_values value_row
    on value_row.report_id = r.id
   and value_row.indicator_key = required_field.indicator_key
   and value_row.dimension_key = required_field.dimension_key
   and value_row.value is not null
  where r.id = p_report_id
    and value_row.id is null;

  if v_missing_count > 0 then
    raise exception 'All required manual M1 BRGY values must be encoded before submission (% missing).', v_missing_count using errcode = '22023';
  end if;
end;
$$;

create or replace function public.submit_fhsis_report(p_report_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare v_role text; v_report public.fhsis_reports%rowtype;
begin
  select p.role into v_role from public.profiles p where p.id = auth.uid();
  if v_role is distinct from 'nurse' then raise exception 'Only a Nurse can submit an FHSIS report.' using errcode = '42501'; end if;
  select * into v_report from public.fhsis_reports where id = p_report_id for update;
  if not found or v_report.created_by <> auth.uid() then raise exception 'FHSIS report not found.' using errcode = '42501'; end if;
  if v_report.status not in ('draft', 'returned') then raise exception 'Only a draft or returned FHSIS report can be submitted.' using errcode = '22023'; end if;
  perform public.fhsis_require_complete_manual_values(p_report_id);
  perform pg_catalog.set_config('medisens.fhsis_transition', 'on', true);
  update public.fhsis_reports set status = 'for_verification', submitted_at = now() where id = p_report_id;
end;
$$;

revoke all on function public.fhsis_require_complete_manual_values(uuid) from public, anon, authenticated;
revoke all on function public.submit_fhsis_report(uuid) from public, anon;
grant execute on function public.submit_fhsis_report(uuid) to authenticated;
