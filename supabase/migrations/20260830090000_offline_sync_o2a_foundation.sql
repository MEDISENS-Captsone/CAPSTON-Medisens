create or replace function public.patient_update(p_operation_id uuid, p_patient_id bigint, p_base_revision integer, p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role text;
  v_existing public.applied_operations%rowtype;
  v_current_revision integer;
  v_new_revision integer;
  v_set text := '';
  v_key text;
  v_allowed text[] := array[
    'firstName', 'middleName', 'lastName', 'suffix', 'age', 'sex', 'civilStatus', 'birthday', 'nationality',
    'bloodType', 'religion', 'birthPlace', 'address', 'contactNumber', 'educationalAttain', 'employmentStatus',
    'philhealthNo', 'philhealthStatus', 'category', 'categoryOthers', 'relativeName', 'relativeRelation',
    'relativeAddress', 'relativeContact'
  ];
  v_result jsonb;
begin
  if p_operation_id is null then
    return jsonb_build_object('outcome', 'validation_failed', 'message', 'operationId is required');
  end if;

  select p.role into v_role from public.profiles p where p.id = (select auth.uid());
  if coalesce(v_role, '') not in ('BHW', 'nurse', 'doctor', 'midwives') then
    return jsonb_build_object('outcome', 'unauthorized');
  end if;

  select * into v_existing from public.applied_operations
  where operation_id = p_operation_id and entity_type = 'patient' and operation_type = 'update';
  if found then
    return v_existing.result || jsonb_build_object('outcome', 'already_applied');
  end if;

  select revision into v_current_revision from public.patients where id = p_patient_id for update;
  if not found then
    return jsonb_build_object('outcome', 'validation_failed', 'message', 'patient not found');
  end if;

  if v_current_revision is distinct from p_base_revision then
    return jsonb_build_object('outcome', 'conflict', 'currentRevision', v_current_revision);
  end if;

  for v_key in select jsonb_object_keys(p_payload) loop
    if v_key = any(v_allowed) then
      v_set := v_set || format('%I = %L, ', v_key, p_payload->>v_key);
    end if;
  end loop;

  if v_set = '' then
    return jsonb_build_object('outcome', 'validation_failed', 'message', 'no updatable fields provided');
  end if;
  v_set := left(v_set, length(v_set) - 2);

  begin
    execute format('update public.patients set %s where id = %L', v_set, p_patient_id);
  exception when others then
    return jsonb_build_object('outcome', 'invalid_transition', 'message', sqlerrm);
  end;

  select revision into v_new_revision from public.patients where id = p_patient_id;
  v_result := jsonb_build_object('outcome', 'success', 'serverId', p_patient_id, 'revision', v_new_revision);

  insert into public.applied_operations (operation_id, entity_type, operation_type, actor_id, server_record_id, result)
  values (p_operation_id, 'patient', 'update', (select auth.uid()), p_patient_id, v_result);

  return v_result;
end;
$$;

revoke all on function public.patient_update(uuid, bigint, integer, jsonb) from public, anon;
grant execute on function public.patient_update(uuid, bigint, integer, jsonb) to authenticated;

-- ---- 3b. Initial consultation + vitals (extend, don't replace) ----
-- record_initial_intake's signature grows an optional trailing
-- parameter, so every existing caller (which never passes it) keeps
-- returning a bare bigint exactly as before -- true backward
-- compatibility, not just "the new default happens to match old
-- behavior". Only when p_operation_id is supplied does idempotency
-- bookkeeping activate at all; a null operation id (today's only caller)
-- skips the applied_operations table entirely, identical to pre-O2A
-- behavior.
-- CREATE OR REPLACE cannot widen a function's signature in place --
-- Postgres treats (jsonb, jsonb) and (jsonb, jsonb, uuid) as distinct
-- overloads, which would leave BOTH versions callable and break
-- PostgREST's RPC dispatch (it cannot disambiguate an ambiguous 2-arg
-- call once a 3-arg overload also matches by name). The original
-- 2-argument function must be dropped first so the 3-argument version
-- with a default becomes the only overload -- this is what actually
-- preserves "existing callers who never pass p_operation_id keep
-- working unchanged", not merely giving the new parameter a default.
drop function if exists public.record_initial_intake(jsonb, jsonb);

create or replace function public.record_initial_intake(p_initial jsonb, p_vitals jsonb, p_operation_id uuid default null)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role text;
  v_patient_id public.patients.id%type;
  v_vitals_patient_id public.patients.id%type;
  v_initial_consultation_id bigint;
  v_existing public.applied_operations%rowtype;
begin
  select p.role
  into v_role
  from public.profiles p
  where p.id = (select auth.uid());

  if coalesce(v_role, '') not in ('nurse', 'midwives') then
    raise exception 'Initial intake is restricted to nurses and midwives' using errcode = '42501';
  end if;

  if p_operation_id is not null then
    select * into v_existing from public.applied_operations
    where operation_id = p_operation_id and entity_type = 'initial_consultation' and operation_type = 'create';
    if found then
      return (v_existing.result->>'serverId')::bigint;
    end if;
  end if;

  v_patient_id := p_initial ->> 'patient_id';
  v_vitals_patient_id := p_vitals ->> 'patient_id';

  if v_patient_id is null or v_vitals_patient_id is distinct from v_patient_id then
    raise exception 'Initial intake and vital signs must reference the same patient';
  end if;

  if not exists (
    select 1 from public.patients p where p.id = v_patient_id
  ) then
    raise exception 'Initial intake requires a valid patient';
  end if;

  insert into public.initial_consultation (
    patient_id,
    consultation_date,
    consultation_time,
    mode_of_transaction,
    referred_by,
    mode_of_transfer,
    chief_complaint,
    diagnosis,
    visit_disposition
  ) values (
    v_patient_id,
    p_initial ->> 'consultation_date',
    p_initial ->> 'consultation_time',
    p_initial ->> 'mode_of_transaction',
    p_initial ->> 'referred_by',
    p_initial ->> 'mode_of_transfer',
    p_initial ->> 'chief_complaint',
    p_initial ->> 'diagnosis',
    p_initial ->> 'visit_disposition'
  )
  returning initialconsultation_id into v_initial_consultation_id;

  insert into public.vital_sign (
    patient_id,
    initial_consultation_id,
    bp,
    heart_rate,
    respiratory_rate,
    temperature,
    o2_saturation,
    weight,
    height,
    nutritional_status,
    bmi,
    visual_acuity_left,
    visual_acuity_right,
    general_survey
  ) values (
    v_patient_id,
    v_initial_consultation_id,
    p_vitals ->> 'bp',
    nullif(p_vitals ->> 'heart_rate', '')::numeric,
    nullif(p_vitals ->> 'respiratory_rate', '')::numeric,
    nullif(p_vitals ->> 'temperature', '')::numeric,
    nullif(p_vitals ->> 'o2_saturation', '')::numeric,
    nullif(p_vitals ->> 'weight', '')::numeric,
    nullif(p_vitals ->> 'height', '')::numeric,
    p_vitals ->> 'nutritional_status',
    nullif(p_vitals ->> 'bmi', '')::numeric,
    p_vitals ->> 'visual_acuity_left',
    p_vitals ->> 'visual_acuity_right',
    p_vitals ->> 'general_survey'
  );

  if p_operation_id is not null then
    insert into public.applied_operations (operation_id, entity_type, operation_type, actor_id, server_record_id, result)
    values (
      p_operation_id, 'initial_consultation', 'create', (select auth.uid()), v_initial_consultation_id,
      jsonb_build_object('outcome', 'success', 'serverId', v_initial_consultation_id, 'revision', 1)
    );
  end if;

  return v_initial_consultation_id;
end;
$$;

