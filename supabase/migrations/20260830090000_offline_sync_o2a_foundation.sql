-- Offline <-> Online Sync Phase O2A: schema verification + sync safety
-- foundation. This migration does NOT implement offline storage or
-- synchronization -- it only adds the minimum backend primitives a future
-- offline outbox will need: a revision counter for stale-write detection,
-- an idempotency ledger for safe replay, and validated write-path RPCs
-- that enforce both.
--
-- Live schema verified against the linked project (information_schema /
-- pg_catalog) before writing this migration -- see the O2A report for the
-- full verification output. Notable confirmed facts that shape this file:
--   - patients.id is `generated always as identity` (bigint) -- callers
--     never supply it; patient_create() below relies purely on the
--     column default.
--   - consultation_id / followup_id / initialconsultation_id / vitals_id
--     are all `generated by default as identity` (bigint).
--   - patient_consent already has a `unique (patient_id)` constraint --
--     out of scope for O2A (not one of the four listed sync-eligible
--     tables), left untouched.
--   - guard_consultation_integrity(), guard_follow_up_integrity(), and
--     guard_initial_consultation_visit_disposition() all do whole-row
--     jsonb diffs excluding a fixed column list to enforce "only these
--     fields may change". The new revision/updated_at columns are NOT in
--     those excluded-column lists, so the new bump-revision trigger on
--     each table is named to fire alphabetically AFTER the existing
--     guard trigger (prefixed zz_) -- by the time the guard trigger
--     inspects NEW, revision/updated_at are still unchanged (a plain
--     client UPDATE never sets them), so no existing guard is tripped.
--     Only after the guard passes does this migration's trigger bump
--     revision/updated_at. This avoids touching the existing guard
--     function bodies at all.

-- ============================================================
-- 1. Shared revision/updated_at columns + trigger
-- ============================================================

alter table public.patients
  add column if not exists revision integer not null default 1,
  add column if not exists updated_at timestamptz not null default now();

alter table public.consultation
  add column if not exists revision integer not null default 1,
  add column if not exists updated_at timestamptz not null default now();

alter table public.follow_up
  add column if not exists revision integer not null default 1,
  add column if not exists updated_at timestamptz not null default now();

alter table public.initial_consultation
  add column if not exists revision integer not null default 1,
  add column if not exists updated_at timestamptz not null default now();

-- One shared trigger function (generalizes the existing bespoke
-- fhsis_set_updated_at() pattern). UPDATE-only by design -- INSERT
-- defaults (revision=1, updated_at=now()) already cover row creation, so
-- this function is never attached to a BEFORE INSERT trigger and never
-- touches inserts. Only bumps when the row's *other* columns actually
-- changed (a resubmitted, content-identical UPDATE does not consume a
-- revision), which matters for retried/replayed writes.
create or replace function public.bump_revision()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (to_jsonb(new) - 'revision' - 'updated_at') is distinct from (to_jsonb(old) - 'revision' - 'updated_at') then
    new.revision := old.revision + 1;
    new.updated_at := now();
  else
    new.revision := old.revision;
    new.updated_at := old.updated_at;
  end if;
  return new;
end;
$$;

revoke all on function public.bump_revision() from public, anon, authenticated;

-- Trigger names prefixed zz_ so they fire after any existing guard
-- trigger on the same table (Postgres fires same-timing triggers in name
-- order). Confirmed via live pg_catalog inspection that none of these
-- four tables already had an updated_at/revision-style trigger, so there
-- is no double-increment risk to guard against.
drop trigger if exists zz_bump_revision on public.patients;
create trigger zz_bump_revision
  before update on public.patients
  for each row execute function public.bump_revision();

drop trigger if exists zz_bump_revision on public.consultation;
create trigger zz_bump_revision
  before update on public.consultation
  for each row execute function public.bump_revision();

drop trigger if exists zz_bump_revision on public.follow_up;
create trigger zz_bump_revision
  before update on public.follow_up
  for each row execute function public.bump_revision();

drop trigger if exists zz_bump_revision on public.initial_consultation;
create trigger zz_bump_revision
  before update on public.initial_consultation
  for each row execute function public.bump_revision();

-- ============================================================
-- 2. Idempotency ledger
-- ============================================================
-- Deliberately minimal -- no clinical payload is stored here, only the
-- small structured `result` a replayed call should return verbatim.
-- RLS is enabled with zero grants/policies for ordinary roles, so this
-- table is reachable only from SECURITY DEFINER functions (which run as
-- the table owner and bypass RLS) -- no direct client select/insert is
-- possible, preventing spoofing or cross-actor reads of unrelated
-- operations.
create table if not exists public.applied_operations (
  operation_id uuid primary key,
  entity_type text not null check (entity_type in ('patient', 'initial_consultation', 'consultation', 'follow_up')),
  operation_type text not null check (operation_type in ('create', 'update')),
  actor_id uuid not null references auth.users(id),
  server_record_id bigint,
  result jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.applied_operations enable row level security;
revoke all on public.applied_operations from public, anon, authenticated;

-- ============================================================
-- 3. Conflict-safe write paths
-- ============================================================
-- All four RPCs below share the same outcome contract so future sync
-- code never has to parse a generic Postgres exception to know what
-- happened:
--   {"outcome": "success", "serverId": ..., "revision": ...}
--   {"outcome": "already_applied", ...same shape as the original success result}
--   {"outcome": "conflict", "currentRevision": ...}          -- UPDATE only
--   {"outcome": "invalid_transition", "message": "..."}      -- a guard/trigger rejected the write
--   {"outcome": "unauthorized"}
--   {"outcome": "validation_failed", "message": "..."}
-- None of these are raised as bare exceptions -- every expected failure
-- mode returns a normal jsonb value the caller can branch on. Role
-- checks mirror the existing RLS policies exactly (defense in depth,
-- same convention as record_initial_intake); RLS itself is unchanged and
-- remains the real enforcement boundary since these functions still only
-- ever act as the calling user's own identity (auth.uid()), never a
-- service-role bypass.

